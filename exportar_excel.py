"""
exportar_excel.py — el Excel de resultados: veredicto primero, datos normalizados.

El export anterior volcaba un DataFrame: una hoja `Sheet1` sin formato, con `Tier` como
numero suelto, el puntaje mezclado con la cadena "Manual", el salario como texto crudo
(imposible de ordenar o filtrar) y nada de lo que el scorer ya habia calculado —veredicto
de ubicacion, requisitos que faltan, cobertura—. Quien lo abria tenia que volver a decidir
a mano, fila por fila, lo que GEMA ya sabia.

Este modulo arma el libro con tres hojas, en este orden:

  1. **Resumen** — la foto de la corrida: totales por tier, por veredicto de ubicacion,
     por fuente, salarios publicados y cobertura de requisitos.
  2. **Avisos** — UNA tabla de Excel con todos los tiers. Las columnas arrancan por lo
     que decide si un aviso se mira (Tier, Score, Ubicacion, Motivos) y siguen con los
     datos. Filas por Tier y Score descendente.
  3. **Revision manual** — lo que NO entro al shortlist pero tampoco se tira: la pila de
     avisos con titulo y empresa reales y URL sin verificar, y los no elegibles
     (vencidos, duplicados, vetos) con su motivo. Un dato rescatable no se descarta.

Normalizacion: celda vacia en lugar de `None`/"nan"; sin comillas que envuelvan el texto;
espacios colapsados; booleanos como Si/No; numeros como numeros (puntaje, porcentaje,
salario); fechas como fecha de Excel.

Seguridad: el titulo, la empresa y la URL los escribio un board. Todo texto pasa por
`excel_seguro.limpiar_celda` y se fuerza a cadena (`data_type == "s"`): una celda que
empieza con `=`, `+`, `-` o `@` se ve igual pero Excel no la evalua. Solo se enlazan URLs
http/https (`excel_seguro.es_url_enlazable`).

Generated by: api.py (GET /api/export.xlsx)
Consumed by:  el usuario, en Excel
"""

