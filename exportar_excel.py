def texto(valor, *, placeholder: str = "") -> str:
    """
    Texto limpio para una celda, o "" si no hay dato.

    Vacio real para None, NaN y las cadenas "None"/"nan"/"null"; entidades HTML
    resueltas; espacios colapsados; sin las comillas que envuelven TODO el texto
    (`'"Acme"'` -> `Acme`; las del interior se respetan: `Acme "Labs"` no cambia).
    """
    if valor is None:
        return ""
    if isinstance(valor, float) and valor != valor:   # NaN
        return ""
    s = limpiar_celda(valor)
    s = html.unescape(s)
    s = re.sub(r"\s+", " ", s).strip()
    cambio = True
    while cambio and len(s) >= 2:
        cambio = False
        for abre, cierra in _COMILLAS:
            if s[0] == abre and s[-1] == cierra and abre not in s[1:-1]:
                s = s[1:-1].strip()
                cambio = True
                break
    if not s or s.lower() in _NULOS:
        return ""
    if placeholder and s.lower() == placeholder.lower():
        return ""
    return s


def si_no(valor) -> str:
    """Booleano como «Sí»/«No»; vacio si no hay dato."""
    if valor is None or (isinstance(valor, float) and valor != valor):
        return ""
    if isinstance(valor, str):
        v = valor.strip().lower()
        if v in ("1", "true", "si", "sí", "yes", "y", "s"):
            return "Sí"
        if v in ("0", "false", "no", "n"):
            return "No"
        return ""
    return "Sí" if valor else "No"


def a_fecha(valor) -> Optional[date]:
    """
    Una fecha de cualquier fuente (datetime, ISO, RFC-2822, epoch de 10/13 digitos) a
    `date`, o None. Reutiliza el parser del registro para que el Excel y el barrido de
    vencidos lean el mismo formato igual.
    """
    if valor is None:
        return None
    if isinstance(valor, datetime):
        if valor.tzinfo is not None:
            valor = valor.astimezone(timezone.utc)
        return valor.date()
    if isinstance(valor, date):
        return valor
    try:
        from database import GemaDatabase
        iso = GemaDatabase._a_fecha(valor)
    except Exception:
        iso = None
    if not iso:
        return None
    try:
        return date.fromisoformat(iso)
    except ValueError:
        return None


