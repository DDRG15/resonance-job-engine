def _faltantes(tj: TieredJob) -> list[str]:
    """Requisitos REQUERIDOS que el CV no cubre (los deseables no cuentan como falta)."""
    vistos, salida = set(), []
    for r in tj.requisitos or []:
        if r.get("estado") == "missing" and r.get("peso") == "requerido":
            nombre = texto(r.get("requisito"))
            if nombre and nombre.lower() not in vistos:
                vistos.add(nombre.lower())
                salida.append(nombre)
    return salida


def _recortar(s: str, tope: int) -> str:
    return s if len(s) <= tope else s[: tope - 1].rstrip() + "…"


def motivos(tj: TieredJob) -> str:
    """
    El «por que» de la fila en pocas palabras, armado con lo que el scorer ya calculo.
    Primero lo que frena (veto o marca de ubicacion/idioma), despues salario y
    requisitos, al final lo que suma. No inventa nada: cada pieza sale de un campo.
    """
    partes: list[str] = []
    if tj.location_verdict in ("FAIL", "FLAG"):
        nota = texto(tj.location_note)
        partes.append(f"Ubicación {tj.location_verdict}" + (f": {nota}" if nota else ""))
    if tj.language_verdict in ("FAIL", "FLAG"):
        nota = texto(tj.language_note)
        partes.append(f"Idioma {tj.language_verdict}" + (f": {nota}" if nota else ""))
    if tj.salario_no_confirmado:
        partes.append("Salario no confirmado")
    faltan = _faltantes(tj)
    if faltan:
        partes.append(f"Faltan {len(faltan)} requisito(s) requerido(s)")
    if tj.cobertura_requisitos is not None:
        partes.append(f"Cubre {tj.cobertura_requisitos:.0%} de los requisitos")

    titulo_pct = None
    skills: list[str] = []
    for razon in tj.match_reasons or []:
        m = re.match(r"Title match (\d+)%", razon)
        if m and titulo_pct is None:
            titulo_pct = m.group(1)
            continue
        m = re.match(r"Skill/signal match: '(.+)'", razon)
        if m and m.group(1) not in skills:
            skills.append(m.group(1))
    if titulo_pct is not None:
        partes.append(f"Título coincide {titulo_pct}%")
    if skills:
        partes.append("Skills: " + ", ".join(skills[:5]))
    return _recortar(" · ".join(partes), _MAX_MOTIVOS)


def _clave_orden(tj: TieredJob) -> tuple:
    return (_ORDEN_TIER.get(tj.tier, 9), -tj.match_score, texto(tj.job.title).lower())


def _aplanar(tiers: dict) -> list[TieredJob]:
    todos = [tj for lista in (tiers or {}).values() for tj in (lista or [])]
    return sorted(todos, key=_clave_orden)


