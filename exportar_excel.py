def construir_excel(tiers: dict[str, list[TieredJob]],
                    manual_review: Optional[list[dict]] = None,
                    no_elegibles: Optional[list[TieredJob]] = None,
                    meta: Optional[dict] = None) -> bytes:
    """
    El libro de resultados como bytes (.xlsx).

    `tiers`: {"tier1": [...], "tier2": [...], "tier3": [...]} (las claves no importan; manda
    `TieredJob.tier`). `manual_review`: filas de `GemaDatabase.get_manual_review`.
    `no_elegibles`: avisos puntuados que no entraron al shortlist. `meta` (todo opcional):
    `fecha` (de la corrida) y `causas` ({url: "Vencido" | "Duplicado" | ...}, para los
    no elegibles cuya causa no queda en el TieredJob).
    """
    meta = meta or {}
    causas = meta.get("causas") or {}
    ordenados = _aplanar(tiers)

    wb = Workbook()
    # Sin datos personales en las propiedades: ni autor del sistema ni usuario.
    wb.properties.creator = "Resonance"
    wb.properties.lastModifiedBy = "Resonance"
    wb.properties.title = "Resonance — resultados"

    # La hoja que openpyxl crea de fabrica pasa a ser «Resumen» (queda primera y activa);
    # «Avisos» y «Revisión manual» se agregan detras en ese orden. El resumen necesita
    # los conteos de la revision, asi que se escribe al final sobre esa primera hoja.
    _hoja_avisos(wb, ordenados)
    _, n_revision = _hoja_revision(wb, manual_review, no_elegibles, causas)
    _hoja_resumen(wb, ordenados, n_revision, len(manual_review or []),
                  len(no_elegibles or []), meta)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
