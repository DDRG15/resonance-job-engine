def _poner(hoja, fila: int, col: int, valor, *, formato: Optional[str] = None,
           ajustar: bool = False, centrar: bool = False):
    """
    Escribe `valor` en la celda. Cadena -> texto seguro (data_type "s"); numero y fecha
    se escriben tipados; "" / None deja la celda vacia.
    """
    celda = hoja.cell(row=fila, column=col)
    if valor is None or valor == "":
        pass
    elif isinstance(valor, str):
        celda.value = valor
        celda.data_type = "s"      # un `=...` queda como texto, nunca como formula
    else:
        celda.value = valor
    if formato:
        celda.number_format = formato
    celda.alignment = Alignment(
        vertical="top", wrap_text=ajustar,
        horizontal="center" if centrar else None)
    return celda


def _poner_enlace(hoja, fila: int, col: int, url, etiqueta: str = "Abrir aviso"):
    """Enlace clicable con texto corto si la URL es http/https; si no, la URL como texto."""
    crudo = texto(url)
    if not crudo:
        return _poner(hoja, fila, col, "")
    if es_url_enlazable(crudo):
        celda = _poner(hoja, fila, col, etiqueta)
        celda.hyperlink = crudo
        celda.font = Font(color="0563C1", underline="single")
        return celda
    return _poner(hoja, fila, col, crudo)


def _encabezado(hoja, fila: int, col: int, titulo: str):
    celda = hoja.cell(row=fila, column=col, value=titulo)
    celda.data_type = "s"
    celda.font = Font(bold=True, color=_ENCABEZADO_TEXTO)
    celda.fill = PatternFill("solid", start_color=_ENCABEZADO_FONDO, end_color=_ENCABEZADO_FONDO)
    celda.alignment = Alignment(vertical="center", horizontal="left", wrap_text=True)
    return celda


def _anchos(hoja, anchos: tuple):
    for i, ancho in enumerate(anchos, start=1):
        hoja.column_dimensions[get_column_letter(i)].width = ancho


def _tabla(hoja, nombre: str, columnas: tuple, n_filas: int, estilo: str):
    """Tabla real de Excel sobre A1:<ultima>. Con 0 filas no se crea: Excel exige al menos
    una fila de datos y "repara" el archivo si la tabla es solo el encabezado."""
    if n_filas <= 0:
        return None
    ref = f"A1:{get_column_letter(len(columnas))}{n_filas + 1}"
    tabla = Table(displayName=nombre, ref=ref)
    tabla.tableStyleInfo = TableStyleInfo(
        name=estilo, showRowStripes=True, showColumnStripes=False,
        showFirstColumn=False, showLastColumn=False)
    tabla.autoFilter = AutoFilter(ref=ref)
    hoja.add_table(tabla)
    return tabla


def _formato_condicional_tier(hoja, col: str, ultima: int):
    rango = f"{col}2:{col}{ultima}"
    for nombre, tinta in _TIER_INK.items():
        hoja.conditional_formatting.add(rango, CellIsRule(
            operator="equal", formula=[f'"{nombre}"'],
            fill=PatternFill("solid", start_color=tinta, end_color=tinta, bgColor=tinta),
            font=Font(bold=True, color=_TEXTO_OSCURO)))


def _formato_condicional_ubicacion(hoja, col: str, ultima: int):
    rango = f"{col}2:{col}{ultima}"
    for veredicto, (fondo, tinta) in _SEMAFORO.items():
        hoja.conditional_formatting.add(rango, CellIsRule(
            operator="equal", formula=[f'"{veredicto}"'],
            fill=PatternFill("solid", start_color=fondo, end_color=fondo, bgColor=fondo),
            font=Font(bold=True, color=tinta)))


def _formato_condicional_score(hoja, col: str, ultima: int):
    """Escala secuencial de un solo matiz (blanco -> teal del Tier 1): se lee sin
    depender de distinguir rojo de verde. Texto oscuro sobre todo el rango."""
    hoja.conditional_formatting.add(f"{col}2:{col}{ultima}", ColorScaleRule(
        start_type="num", start_value=0, start_color="FFFFFF",
        end_type="num", end_value=100, end_color=_TIER_INK["Tier 1"]))


