def _origen_no_elegible(tj: TieredJob, causas: dict) -> tuple[str, str]:
    """(origen, motivo) de un no elegible. La causa explicita de `meta['causas']` (por
    URL) manda: el vencido y el duplicado no dejan marca en el TieredJob."""
    causa = causas.get(tj.job.url) if causas else None
    if causa:
        causa = texto(causa)
        if causa == "Vencido":
            vence = a_fecha(tj.job.deadline)
            return causa, (f"Venció el {vence.isoformat()}" if vence else _MOTIVOS_CAUSA[causa])
        return causa, _MOTIVOS_CAUSA.get(causa) or motivos(tj)
    if tj.location_verdict == "FAIL":
        return "Veto de ubicación", texto(tj.location_note)
    if tj.language_verdict == "FAIL":
        return "Veto de idioma", texto(tj.language_note)
    vence = a_fecha(tj.job.deadline)
    if vence is not None and vence < date.today():
        return "Vencido", f"Venció el {vence.isoformat()}"
    return "No elegible", motivos(tj)


def _hoja_revision(wb: Workbook, manual_review: list, no_elegibles: list, causas: dict):
    hoja = wb.create_sheet(HOJA_REVISION)
    for c, nombre in enumerate(COLUMNAS_REVISION, start=1):
        _encabezado(hoja, 1, c, nombre)
    hoja.row_dimensions[1].height = 32

    filas = []
    for r in manual_review or []:
        resuelta = bool(r.get("resolved"))
        codigo = texto(r.get("reason"))
        filas.append({
            "origen": "Pila de revisión (resuelta)" if resuelta else "Pila de revisión",
            "motivo": _MOTIVOS_PILA.get(codigo, codigo.replace("_", " ")),
            "titulo": texto(r.get("title")),
            "empresa": texto(r.get("company"), placeholder=_PLACEHOLDER_EMPRESA),
            "ubicacion": "", "fuente": texto(r.get("source_domain")), "score": None,
            "capturado": a_fecha(r.get("captured_at")),
            "resuelto": si_no(resuelta),
            "url": r.get("resolved_url") if resuelta else None,
            "sin_verificar": r.get("original_url"),
            "listado": r.get("srp_url"),
            "orden": (0, 0 if not resuelta else 1, 0),
        })
    for tj in sorted(no_elegibles or [], key=_clave_orden):
        origen, motivo = _origen_no_elegible(tj, causas)
        j = tj.job
        filas.append({
            "origen": origen, "motivo": motivo, "titulo": texto(j.title),
            "empresa": texto(j.company, placeholder=_PLACEHOLDER_EMPRESA),
            "ubicacion": texto(j.location_raw), "fuente": texto(j.source_domain),
            "score": tj.match_score,
            "capturado": a_fecha(j.scraped_at), "resuelto": "",
            "url": j.url, "sin_verificar": None, "listado": None,
            "orden": (1, origen, -tj.match_score),
        })
    filas.sort(key=lambda f: f["orden"])

    for i, f in enumerate(filas, start=2):
        _poner(hoja, i, 1, f["origen"], ajustar=True)
        _poner(hoja, i, 2, f["motivo"], ajustar=True)
        _poner(hoja, i, 3, f["titulo"], ajustar=True)
        _poner(hoja, i, 4, f["empresa"], ajustar=True)
        _poner(hoja, i, 5, f["ubicacion"], ajustar=True)
        _poner(hoja, i, 6, f["fuente"])
        _poner(hoja, i, 7, f["score"], formato="0", centrar=True)
        _poner(hoja, i, 8, f["capturado"], formato="yyyy-mm-dd", centrar=True)
        _poner(hoja, i, 9, f["resuelto"], centrar=True)
        _poner_enlace(hoja, i, 10, f["url"])
        _poner_enlace(hoja, i, 11, f["sin_verificar"], "Abrir (sin verificar)")
        _poner_enlace(hoja, i, 12, f["listado"], "Abrir listado")

    if not filas:
        hoja.cell(row=2, column=1, value="Nada en revisión manual.").data_type = "s"
    _tabla(hoja, "TablaRevision", COLUMNAS_REVISION, len(filas), "TableStyleMedium9")
    hoja.freeze_panes = "A2"
    _anchos(hoja, (26, 46, 44, 26, 24, 22, 8, 12, 10, 14, 20, 16))
    _preparar_impresion(hoja)
    return hoja, len(filas)


def _preparar_impresion(hoja):
    hoja.page_setup.orientation = "landscape"
    hoja.page_setup.fitToWidth = 1
    hoja.page_setup.fitToHeight = 0
    hoja.sheet_properties.pageSetUpPr.fitToPage = True
    hoja.print_title_rows = "1:1"


