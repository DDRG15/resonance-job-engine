def _hoja_avisos(wb: Workbook, ordenados: list[TieredJob]):
    hoja = wb.create_sheet(HOJA_AVISOS)
    for c, nombre in enumerate(COLUMNAS_AVISOS, start=1):
        _encabezado(hoja, 1, c, nombre)
    hoja.row_dimensions[1].height = 32

    for i, tj in enumerate(ordenados, start=2):
        j = tj.job
        sal = salario_anual_usd(j.salary_raw)
        puntaje = tj.match_score
        cob = tj.cobertura_requisitos
        vals = (
            (tj.tier, None, False, True),
            (puntaje, "0", False, True),
            (tj.location_verdict, None, False, True),
            (motivos(tj), None, True, False),
            (texto(j.title), None, True, False),
            (texto(j.company, placeholder=_PLACEHOLDER_EMPRESA), None, True, False),
            (texto(j.location_raw), None, True, False),
            (sal, "#,##0", False, False),
            (texto(j.salary_raw), None, True, False),
            (cob, "0%", False, True),
            (", ".join(_faltantes(tj)), None, True, False),
            (texto(j.source_domain), None, False, False),
            (a_fecha(j.scraped_at), "yyyy-mm-dd", False, True),
            (a_fecha(j.deadline), "yyyy-mm-dd", False, True),
        )
        for c, (v, fmt, ajustar, centrar) in enumerate(vals, start=1):
            _poner(hoja, i, c, v, formato=fmt, ajustar=ajustar, centrar=centrar)
        _poner_enlace(hoja, i, len(COLUMNAS_AVISOS), j.url)

    ultima = max(len(ordenados) + 1, 2)
    if not ordenados:
        hoja.cell(row=2, column=1, value="Sin avisos en esta corrida.").data_type = "s"
    _tabla(hoja, "TablaAvisos", COLUMNAS_AVISOS, len(ordenados), "TableStyleMedium2")
    hoja.freeze_panes = "A2"
    _anchos(hoja, (9, 8, 11, 58, 44, 26, 26, 14, 22, 12, 34, 22, 12, 12, 14))
    _formato_condicional_tier(hoja, "A", ultima)
    _formato_condicional_score(hoja, "B", ultima)
    _formato_condicional_ubicacion(hoja, "C", ultima)
    _preparar_impresion(hoja)
    return hoja


