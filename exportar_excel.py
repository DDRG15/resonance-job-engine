def _bloque(hoja, fila: int, titulo: str, columnas: tuple, filas: list[tuple],
            formatos: tuple) -> int:
    """Una tabla chica (titulo + encabezado + filas). Devuelve la fila libre siguiente."""
    t = hoja.cell(row=fila, column=1, value=titulo)
    t.data_type = "s"
    t.font = Font(bold=True, size=12)
    fila += 1
    for c, nombre in enumerate(columnas, start=1):
        _encabezado(hoja, fila, c, nombre)
    for f in filas:
        fila += 1
        for c, v in enumerate(f, start=1):
            celda = _poner(hoja, fila, c, v, formato=formatos[c - 1] if c <= len(formatos) else None)
            celda.border = Border(bottom=_BORDE)
    return fila + 2


def _pct(parte: int, total: int) -> Optional[float]:
    return parte / total if total else None


def _hoja_resumen(wb: Workbook, ordenados: list[TieredJob], n_revision: int,
                  n_pila: int, n_no_elegibles: int, meta: dict):
    hoja = wb.active
    hoja.title = HOJA_RESUMEN
    total = len(ordenados)

    hoja["A1"].value = "Resonance — resumen de la corrida"
    hoja["A1"].font = Font(bold=True, size=16)
    fecha = meta.get("fecha")
    fecha = a_fecha(fecha) if fecha is not None else None
    fecha = fecha or datetime.now(timezone.utc).date()
    hoja["A2"].value = "Fecha de la corrida"
    hoja["B2"].value = fecha
    hoja["B2"].number_format = "yyyy-mm-dd"
    hoja["B2"].alignment = Alignment(horizontal="left")
    hoja["A3"].value = "Avisos en el shortlist"
    hoja["B3"].value = total
    hoja["B3"].number_format = "#,##0"
    hoja["B3"].alignment = Alignment(horizontal="left")
    hoja["A4"].value = "En revisión manual (pila + no elegibles)"
    hoja["B4"].value = n_revision
    hoja["B4"].number_format = "#,##0"
    hoja["B4"].alignment = Alignment(horizontal="left")
    for r in (2, 3, 4):
        hoja.cell(row=r, column=1).font = Font(bold=True)
    fila = 6

    # Por tier
    por_tier = {t: [tj for tj in ordenados if tj.tier == t] for t in _ORDEN_TIER}
    filas = []
    for t, lista in por_tier.items():
        puntajes = [tj.match_score for tj in lista]
        filas.append((t, len(lista), _pct(len(lista), total),
                      round(sum(puntajes) / len(puntajes), 1) if puntajes else None))
    fila = _bloque(hoja, fila, "Por tier", ("Tier", "Avisos", "% del total", "Score promedio"),
                   filas, (None, "#,##0", "0.0%", "0.0"))

    # Por veredicto de ubicacion
    cuenta = {v: sum(1 for tj in ordenados if tj.location_verdict == v) for v in _SEMAFORO}
    filas = [(v, n, _pct(n, total)) for v, n in cuenta.items()]
    fila = _bloque(hoja, fila, "Por veredicto de ubicación",
                   ("Veredicto", "Avisos", "% del total"), filas, (None, "#,##0", "0.0%"))

    # Por fuente
    fuentes: dict[str, list[TieredJob]] = {}
    for tj in ordenados:
        fuentes.setdefault(texto(tj.job.source_domain) or "(sin fuente)", []).append(tj)
    filas = []
    for fuente, lista in sorted(fuentes.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        t1 = sum(1 for tj in lista if tj.tier == "Tier 1")
        filas.append((fuente, len(lista), _pct(len(lista), total), t1, _pct(t1, len(lista))))
    fila = _bloque(hoja, fila, "Por fuente",
                   ("Fuente", "Avisos", "% del total", "En Tier 1", "% de la fuente en Tier 1"),
                   filas, (None, "#,##0", "0.0%", "#,##0", "0.0%"))

    # Salarios
    con = sum(1 for tj in ordenados if salario_anual_usd(tj.job.salary_raw) is not None)
    sin_confirmar = sum(1 for tj in ordenados if tj.salario_no_confirmado)
    sin = total - con - sin_confirmar
    filas = [("Publicado y legible (USD/año)", con, _pct(con, total)),
             ("Publicado en texto, sin confirmar", sin_confirmar, _pct(sin_confirmar, total)),
             ("No publicado", sin, _pct(sin, total))]
    fila = _bloque(hoja, fila, "Salarios", ("Situación", "Avisos", "% del total"), filas,
                   (None, "#,##0", "0.0%"))

    # Requisitos
    cobs = [tj.cobertura_requisitos for tj in ordenados if tj.cobertura_requisitos is not None]
    filas = [("Avisos con requisitos evaluados", len(cobs), _pct(len(cobs), total),
              sum(cobs) / len(cobs) if cobs else None)]
    fila = _bloque(hoja, fila, "Cobertura de requisitos",
                   ("Medida", "Avisos", "% del total", "Cobertura promedio"), filas,
                   (None, "#,##0", "0.0%", "0.0%"))

    # Revision manual
    filas = [("Pila de revisión (URL sin verificar)", n_pila),
             ("No elegibles (vencidos, duplicados, vetos)", n_no_elegibles)]
    _bloque(hoja, fila, "Revisión manual", ("Origen", "Avisos"), filas, (None, "#,##0"))

    _anchos(hoja, (46, 14, 14, 16, 24))
    hoja.sheet_view.showGridLines = False
    return hoja


