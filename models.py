class TieredJob(BaseModel):
    """
    A JobResult enriched with a match score and tier classification.

    Generated by: matcher.py
    Consumed by:  main.py (display), integrations/
    """

    job: JobResult
    match_score: int = Field(
        ...,
        ge=0,
        le=115,
        description=(
            "0–115 match score for scored tiers (Tier 1/2/3). "
            "Base is 0–100; the +15 skill-overlap bonus (when CV is loaded) "
            "can push a strong Tier 2 into Tier 1 without changing the 80-pt threshold. "
        ),
    )
    tier: str = Field(..., description="'Tier 1', 'Tier 2', or 'Tier 3'.")
    match_reasons: list[str] = Field(
        default_factory=list,
        description="Human-readable list of which criteria matched.",
    )
    miss_reasons: list[str] = Field(
        default_factory=list,
        description="Human-readable list of which criteria did NOT match.",
    )

    # ── Fase 3 (2026-09-15): la elegibilidad sale del score ──────────────────
    # Antes la ubicacion era un delta que se sumaba al puntaje, y el bloqueo duro
    # ademas forzaba Tier 3 con score 0. Eso destruia informacion: un puesto
    # excelente bloqueado por security clearance y uno genuinamente malo salian
    # identicos. El score mide ajuste; la elegibilidad se responde aparte.
    location_verdict: str = Field(
        default="PASS",
        description=(
            "PASS — nada bloquea. "
            "FLAG — la ubicacion nombra una region restringida pero el aviso no "
            "declara un requisito: queda rankeado con marca. "
            "FAIL — el aviso exige ciudadania, clearance o autorizacion que no "
            "tenes: sale del shortlist CONSERVANDO su puntaje."
        ),
    )
    location_note: str = Field(default="", description="Por que ese veredicto.")
    language_verdict: str = Field(
        default="PASS",
        description=(
            "PASS — no pide un idioma que no hablas. "
            "FLAG — pide uno que hablas, a un nivel que el aviso sugiere mayor. "
            "FAIL — pide un idioma ausente de tu perfil."
        ),
    )
    language_note: str = Field(default="", description="Por que ese veredicto.")

    # ── Match por requisitos ─────────────────────────
    requisitos: list[dict] = Field(
        default_factory=list,
        description=(
            "Requisitos que nombra la descripcion, cada uno con `requisito`, `estado` "
            "(match | missing | implicito), `peso` (requerido | deseable) y `evidencia` "
            "(la frase de la descripcion). Vacio sin descripcion o sin CV cargado: sin CV "
            "todo saldria 'missing', y eso no es un dato sino la falta de uno."
        ),
    )
    cobertura_requisitos: Optional[float] = Field(
        default=None,
        description=(
            "0..1, fraccion ponderada de los requisitos que el CV cubre (deseable pesa la "
            "mitad). None = el eje no participo: sin descripcion, sin CV o con menos de "
            "3 requisitos."
        ),
    )

    @property
    def elegible(self) -> bool:
        """False si algun veto es FAIL. Un FLAG sigue siendo elegible: marcado,
        no descartado — descartar en silencio es peor que mostrar con una nota."""
        return "FAIL" not in (self.location_verdict, self.language_verdict)

    @computed_field
    @property
    def salario_no_confirmado(self) -> bool:
        """
        El aviso publico salario en texto ("Competitive", "DOE") que no se pudo leer
        como sueldo anual. Ya no saca el aviso del
        scoring; se
        puntua sin el eje de salario y se marca. Calculado, no guardado: sale de
        `salary_raw`, asi que una fila vieja lo trae igual y no puede contradecirse.
        No publicar salario NO es esto: es un dato ausente, sin marca.
        """
        crudo = (self.job.salary_raw or "").strip()
        return bool(crudo) and salario_anual_usd(crudo) is None

    @field_validator("tier")
    @classmethod
    def validate_tier(cls, v: str) -> str:
        allowed = {"Tier 1", "Tier 2", "Tier 3"}
        if v not in allowed:
            raise ValueError(f"tier must be one of {allowed}, got '{v}'")
        return v


