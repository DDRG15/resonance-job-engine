#: Tope de `JobResult.descripcion`, medido el 2026-09-30:
#: cubre mas del p90 de Greenhouse, la
#: fuente mas larga (10.178), y el 100% de Himalayas y Remotive. El salario se extrae de
#: la descripcion entera ANTES de recortar, asi que el tope no le quita salarios a nadie.
DESCRIPCION_MAX_CHARS = 12_000


class JobResult(BaseModel):
    """
    Surface metadata extracted by the scraper.

    La regla vieja "sin descripcion" se levanta para las fuentes
    que la traen en el mismo payload (endpoints y ATS): el match por requisitos la lee.
    Se guarda texto limpio con saltos de linea, nunca HTML, con tope de
    `DESCRIPCION_MAX_CHARS`. Las ramas CSS siguen sin descripcion.

    Generated by: scraper.py
    Consumed by:  matcher.py, database.py
    """

    title: str = Field(..., description="Job title as displayed on the listing.")
    company: str = Field(..., description="Company name — fallback key if URL rots.")
    url: str = Field(..., description="Direct link to the job posting.")
    salary_raw: Optional[str] = Field(
        default=None,
        description="Raw salary string as scraped (e.g. '$120k - $150k'). "
                    "None if not published.",
    )
    location_raw: Optional[str] = Field(
        default=None,
        description="Raw location string as scraped (e.g. 'USA', 'Anywhere', 'EMEA'). "
                    "None if not extracted by the board's selector.",
    )
    source_domain: str = Field(..., description="The job board domain this was scraped from.")
    deadline: Optional[str] = Field(
        default=None,
        description=(
            "Fecha limite de postulacion, tal como la publica la fuente. Greenhouse la "
            "entrega en `application_deadline` y el RSS de WeWorkRemotely en `expires_at` "
            "-- 90 de 90 items. Se guarda CRUDA y se normaliza al leerla: los formatos "
            "varian por fuente y reescribir el original pierde la unica evidencia de que "
            "formato hablaba esa fuente el dia que se scrapeo."
        ),
    )
    scraped_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of extraction.",
    )
    descripcion: Optional[str] = Field(
        default=None,
        description=(
            "Texto limpio de la descripcion del aviso, con saltos de linea entre bloques "
            "(los titulos de seccion como 'Nice to have' dependen de ellos). Solo fuentes "
            "que la traen en el payload. None si no hay."
        ),
    )

    @field_validator("descripcion", mode="before")
    @classmethod
    def recortar_descripcion(cls, v):
        """
        Vacio -> None; mas largo que el tope -> recortado en el ultimo salto de linea
        antes del tope (una linea cortada a la mitad puede partir un requisito en dos).
        """
        if v is None:
            return None
        texto = str(v).strip()
        if not texto:
            return None
        if len(texto) <= DESCRIPCION_MAX_CHARS:
            return texto
        corte = texto.rfind("\n", 0, DESCRIPCION_MAX_CHARS)
        return texto[:corte if corte > DESCRIPCION_MAX_CHARS // 2 else DESCRIPCION_MAX_CHARS]

    @field_validator("url", mode="before")
    @classmethod
    def normalize_url(cls, v: str) -> str:
        """Strip trailing slashes and whitespace for consistent hashing."""
        return str(v).strip().rstrip("/")

    @field_validator("title", "company", mode="before")
    @classmethod
    def strip_whitespace(cls, v: str, info) -> str:
        if v is None and info.field_name == "company":
            return ""
        return str(v).strip()

    @field_validator("company", mode="after")
    @classmethod
    def limpiar_empresa(cls, v: str, info) -> str:
        """Separa la empresa del título cuando el selector trajo ambos en el mismo
        nodo (python.org) y quita ruido de scraping. Es identidad sobre un nombre ya
        limpio. Si el campo era solo el título, no hay empresa: queda el marcador
        `(empresa no listada)` y el aviso se conserva."""
        if not v:
            return v
        limpia = normalizar_empresa(v, info.data.get("title", ""))
        return limpia or PLACEHOLDER_EMPRESA

    @computed_field
    @property
    def empresa_no_confirmada(self) -> bool:
        """La UI usa el mismo criterio de calidad que la pila de revisión."""
        return motivo_empresa_dudosa(self.company) is not None

    def parse_salary_usd(self) -> Optional[int]:
        """
        Parses salary_raw to an integer USD annual value.
        Returns None if no currency-anchored amount is found.

        TWO STRICTLY ANCHORED PATHS — no standalone digits accepted:

        Path 1  (dollar prefix):
            Requires a literal $ before the number.
            Matches: '$120k', '$90,000', '$120k - $150k', '$85,000/yr'
            Rejects: anything without a leading $

        Path 2  (usd suffix):
            Requires the word 'usd' immediately after the number/k.
            Matches: '120k usd', '85k USD', '90 usd'
            Rejects: '401k match' — no 'usd' follows the k, so no match

        REJECTS: '401k', '401k match', 'equity', 'DOE', 'Competitive'

        GROUP LAYOUT — 4-tuple per match (alternation produces two pairs):
            (dollar_num, dollar_k, usd_num, usd_k)
            Only ONE pair is populated per match; the other pair is empty.

        DIGIT FLOOR — the {2,3} quantifier requires at least 2 leading
        digits, preventing spurious matches on $1 or $5 text fragments.
        Minimum matchable amount: $10.

        Salary ranges ('$120k - $150k') return the minimum value —
        conservative estimate for the salary gate filter.
        """
        return salario_anual_usd(self.salary_raw)


def salario_anual_usd(texto: Optional[str]) -> Optional[int]:
    """Un texto de salario a USD anuales, o None. Ver `_salario_anual_detalle`."""
    return _salario_anual_detalle(texto)[0]


def _salario_anual_detalle(texto: Optional[str]) -> tuple[Optional[int], bool]:
    """
    (USD anuales o None, si se anualizo desde un periodo no anual).

    Un texto de salario a USD anuales, o None. La logica que vivia en
    JobResult.parse_salary_usd, sacada a modulo el 2026-09-29 para que el extractor
    de descripciones pueda medir cada candidato sin fabricar un JobResult: tiene que
    descartar montos que no son un sueldo anual (ver endpoint_scraper).
    """
    if not texto:
        return None, False

    import re
    # Input is lowercased so the usd\b branch matches 'USD', 'usd', 'Usd'.
    # Currency symbols are not affected by lower().
    raw = texto.lower()

    # Fase 4 (2026-09-15): libras y euros, no solo dólares.
    #
    # El parser reconoce GBP y EUR para que los salarios europeos publicados
    # participen del eje de salario.
    #
    # El anclaje se mantiene igual de estricto: hace falta un símbolo o un código
    # de moneda. Sin eso, "401k match" volvería a parsear como 401.000 — que es
    # el bug que estas dos rutas ancladas existen para prevenir.
    # Tercera ruta (2026-09-29): el codigo DELANTE — "EUR 109,000", "USD 120k" —,
    # que es como Greenhouse publica los rangos europeos. Exige separador de miles
    # o sufijo k a proposito: sin eso, los 10 salarios que el extractor habia
    # truncado a "EUR 109" se leerian como 109 euros al ano. Un salario inventado
    # es peor que ninguno; esos se marcan como salario no confirmado.
    # Y 2-3 digitos iniciales, igual que la ruta del simbolo: 'USD 2,000' es el
    # presupuesto de formacion de Canonical, no un sueldo (medido en 239 avisos).
    #
    # v5 (2026-09-29): un separador seguido de EXACTAMENTE 3 digitos es de miles, sea
    # coma o punto — "€50.000" es la forma europea, y Grafana Labs publico
    # "$154,445 - $185.334" (typo). Leer "185.334" como decimal daba 185 dolares, y como
    # un rango devuelve su minimo, el aviso quedaba con un sueldo de $185. Medido con
    # piso de 90k (el de la busqueda de la API): Tier 2 con 59 puntos leido bien, Tier 3
    # con 25 leido mal ("Salary $185 below minimum"). Con 1-2 digitos sigue siendo
    # decimal ("$85.5k").
    # El PERIODO. Remotive publica "$90 - $150 /hour" y esto
    # devolvia 90 — noventa dolares al ano —, asi que el aviso caia a Tier 3 por
    # "salario por debajo del minimo". Con periodo no anual se multiplica, y se abre
    # la forma de un digito de miles ("$3,500/month") que sin periodo sigue cerrada
    # por el presupuesto de Canonical ("USD 2,000").
    multiplicador, techo = _periodo_del_salario(raw)
    if multiplicador != 1:
        num_sim = r'(?:\d{1,3}(?:[.,]\d{3})+|\d{2,3})(?:\.\d+)?'
        num_pre = r'\d{1,3}(?:[.,]\d{3})+|\d{2,3}(?:\.\d+)?'
    else:
        num_sim = r'\d{2,3}(?:[.,]\d{3})*(?:\.\d+)?'
        num_pre = r'\d{2,3}(?:[.,]\d{3})+|\d{2,3}(?:\.\d+)?(?=\s*k)'
    matches = re.findall(
        rf'([$£€])\s*({num_sim})\s*(k)?'
        r'|'
        r'(\d{2,3}(?:[.,]\d{3})*(?:\.\d+)?)\s*(k)?\s*(usd|eur|gbp)\b'
        r'|'
        rf'\b(usd|eur|gbp)\s*({num_pre})\s*(k)?',
        raw,
    )
    if not matches:
        return None, False

    _SIMBOLO = {"$": "usd", "£": "gbp", "€": "eur"}
    # Import diferido: config importa models en algunos caminos, y un import
    # de módulo acá arriba cerraría el ciclo.
    try:
        import config as _cfg
        tasas = getattr(_cfg, "TASAS_A_USD", None) or {"usd": 1.0}
    except Exception:
        tasas = {"usd": 1.0}

    values = []
    for (simbolo, sym_num, sym_k, cod_num, cod_k, codigo,
         pre_cod, pre_num, pre_k) in matches:
        if sym_num:
            num_str, suffix, moneda = sym_num, sym_k, _SIMBOLO.get(simbolo, "usd")
        elif cod_num:
            num_str, suffix, moneda = cod_num, cod_k, codigo
        elif pre_num:
            num_str, suffix, moneda = pre_num, pre_k, pre_cod
        else:
            continue
        try:
            # Fuera los separadores de miles (coma o punto seguidos de 3 digitos); el
            # punto que queda, si queda, es decimal. Una coma decimal ("120,5k") ya no
            # se convierte en 1.205.000: queda sin parsear y el aviso va a revision.
            val = float(re.sub(r"[.,](?=\d{3}(?:\D|$))", "", num_str))
            if (suffix or "").lower() == "k":
                val *= 1000
            # A USD, que es la moneda en la que está escrito `min_salary`.
            # Convertir acá y no en el gate mantiene una sola unidad aguas abajo.
            values.append(int(val * tasas.get(moneda, 1.0)))
        except ValueError:
            continue

    if not values:
        return None, False
    base = min(values)
    # Solo se anualiza un monto que es plausible para ese periodo. "$150,000 base + 2
    # days per month remote" nombra un mes, pero 150.000 no es un mensual: ya es anual.
    if multiplicador != 1 and base < techo:
        return int(base * multiplicador), True
    return base, False


# Periodo -> (multiplicador a anual, techo por debajo del cual el monto es de ese
# periodo). Los techos son holgados a proposito: un mensual de 60.000 USD o una tarifa
# de 1.000 USD la hora no son sueldos de los boards que GEMA lee; por encima, el
# numero ya es anual y la palabra de periodo habla de otra cosa (PTO, stipend).
_PERIODOS_SALARIO = (
    ("hora", 2080, 1_000,
     r"/\s*(?:hr|hour|h)\b|\bper\s+hour\b|\ban\s+hour\b|\bhourly\b|\bpor\s+hora\b|/\s*hora\b"),
    ("dia", 260, 5_000,
     r"/\s*day\b|\bper\s+day\b|\bdaily\b|\bpor\s+d[ií]a\b|/\s*d[ií]a\b"),
    ("semana", 52, 20_000,
     r"/\s*(?:wk|week)\b|\bper\s+week\b|\ba\s+week\b|\bweekly\b|\bpor\s+semana\b|\bsemanal\b"),
    ("mes", 12, 60_000,
     r"/\s*(?:mo|month)\b|\bper\s+month\b|\ba\s+month\b|\bmonthly\b|\bmensual(?:es)?\b"
     r"|\bal\s+mes\b|\bpor\s+mes\b|/\s*mes\b"),
)
_PERIODO_ANUAL = (r"/\s*(?:yr|year)\b|\bper\s+(?:year|annum)\b|\ba\s+year\b|\bannual(?:ly)?\b"
                  r"|\byearly\b|\bal\s+a[nñ]o\b|\bpor\s+a[nñ]o\b|\banual\b")


def _periodo_del_salario(texto_lower: str) -> tuple[int, int]:
    """
    (multiplicador, techo) del periodo que nombra el texto; (1, 0) si es anual o no
    nombra ninguno.

    Una marca anual explicita gana sobre cualquier otra: "$120k a year + $1k monthly
    stipend" es un sueldo anual con un extra mensual, no un mensual de 120k.
    """
    import re
    if re.search(_PERIODO_ANUAL, texto_lower):
        return 1, 0
    for _nombre, mult, techo, patron in _PERIODOS_SALARIO:
        if re.search(patron, texto_lower):
            return mult, techo
    return 1, 0


def salario_anualizado(texto: Optional[str]) -> bool:
    """True si `salario_anual_usd` multiplico el monto por un periodo no anual. Para la
    metrica `jobs_salario_anualizado`."""
    return _salario_anual_detalle(texto)[1]


